   - 遭遇的危机（妖兽袭击、仇家追杀、门派争斗）
   - 人际关系（结识的同伴、树下的仇敌）
   - 修仙界的时事（宗门大比、正魔大战、天象异变）
   - 一年四季的更替和风物描写

